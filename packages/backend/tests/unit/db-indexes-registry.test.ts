/**
 * Central index registry (GOV-4): src/db/indexes.ts is the one place indexes
 * are declared, and boot applies it after migrations.
 *
 *   - Shape: every registry collection is a known collection; no two entries
 *     of a collection share a name or an identical spec (same key + same
 *     partial filter — Mongo only allows a repeated key when the partial
 *     filter differs).
 *   - Ratchet: `createIndex(` may only appear in src/db and src/migrations.
 *     Anything else creating indexes bypasses the registry (and runs at the
 *     wrong time at boot). Dynamic per-collection cases go through
 *     src/db/indexes.ts too (ensureAgentAppStorageIndexes); the allowlist is
 *     for code that genuinely can't.
 */

import { describe, expect, it } from "bun:test"
import { readdirSync, readFileSync, statSync } from "node:fs"
import { join, relative, resolve } from "node:path"
import { isKnownCollection } from "../../src/db"
import { AGENT_APP_STORAGE_INDEXES, INDEXES, type IndexDef } from "../../src/db/indexes"

const SRC = resolve(__dirname, "../../src")

/** path (relative to src) → why it may call createIndex directly. */
const CREATE_INDEX_ALLOWLIST: Record<string, string> = {
  "scripts/migrate-lastmessageat.ts":
    "one-off historical CLI (lastMessageAt backfill); its {lastMessageAt, channelId} index predates and is superseded by channels.workspaceId_1_lastMessageAt_-1_channelId_1",
}

const CREATE_INDEX = /\bcreateIndex(?:es)?\(/

function sourceFiles(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name)
    if (statSync(path).isDirectory()) return sourceFiles(path)
    return path.endsWith(".ts") && !path.endsWith(".test.ts") ? [path] : []
  })
}

const specKey = (def: IndexDef) =>
  `${JSON.stringify(def.key)}|${JSON.stringify(def.partialFilterExpression ?? null)}`

describe("index registry shape (GOV-4)", () => {
  const entries = Object.entries(INDEXES) as Array<[string, readonly IndexDef[]]>

  it("declares a sane number of collections and indexes", () => {
    expect(entries.length).toBeGreaterThan(80)
    expect(entries.reduce((n, [, defs]) => n + defs.length, 0)).toBeGreaterThan(250)
  })

  it("every collection in the registry is registered in COLLECTIONS", () => {
    expect(entries.map(([name]) => name).filter((name) => !isKnownCollection(name))).toEqual([])
  })

  it("no collection has two entries with the same name", () => {
    const dupes: string[] = []
    for (const [collection, defs] of entries) {
      const seen = new Set<string>()
      for (const def of defs) {
        if (seen.has(def.name)) dupes.push(`${collection}.${def.name}`)
        seen.add(def.name)
      }
    }
    expect(dupes).toEqual([])
  })

  it("no collection has two entries with an identical key (and partial filter)", () => {
    const dupes: string[] = []
    for (const [collection, defs] of entries) {
      const seen = new Map<string, string>()
      for (const def of defs) {
        const k = specKey(def)
        if (seen.has(k)) dupes.push(`${collection}: ${seen.get(k)} vs ${def.name}`)
        seen.set(k, def.name)
      }
    }
    expect(dupes).toEqual([])
  })

  it("every entry has a non-empty key and name, and TTL entries are single-field", () => {
    const bad: string[] = []
    for (const [collection, defs] of [...entries, ["agent_app_storage_*", AGENT_APP_STORAGE_INDEXES] as const]) {
      for (const def of defs) {
        if (!def.name || Object.keys(def.key).length === 0) bad.push(`${collection}.${def.name}`)
        if (def.expireAfterSeconds !== undefined && Object.keys(def.key).length !== 1) {
          bad.push(`${collection}.${def.name} (TTL on a compound key)`)
        }
      }
    }
    expect(bad).toEqual([])
  })

  it("keeps the production names the old boot code created (spot check)", () => {
    const names = (c: string) => (INDEXES as Record<string, readonly IndexDef[]>)[c]?.map((d) => d.name)
    // Auto-generated by the old createIndex calls (no explicit name)
    expect(names("users")).toContain("profile.email_1")
    expect(names("channels")).toContain("workspaceId_1_lastMessageAt_-1_channelId_1")
    // The name boot always used (migration 20261017_002 uses it too)
    expect(names("projects")).toContain("projectId_1")
    expect(names("projects")).not.toContain("projectId_unique")
  })
})

describe("createIndex ratchet (GOV-4)", () => {
  it("createIndex( appears only in src/db, src/migrations and the allowlist", () => {
    const offenders: string[] = []
    for (const path of sourceFiles(SRC)) {
      const rel = relative(SRC, path)
      if (rel.startsWith("db/") || rel.startsWith("migrations/") || rel in CREATE_INDEX_ALLOWLIST) continue
      readFileSync(path, "utf-8")
        .split("\n")
        .forEach((line, i) => {
          const trimmed = line.trim()
          if (trimmed.startsWith("//") || trimmed.startsWith("*")) return
          if (CREATE_INDEX.test(line)) offenders.push(`${rel}:${i + 1}`)
        })
    }
    expect(offenders).toEqual([])
  })

  it("allowlisted files still exist and still need it", () => {
    for (const rel of Object.keys(CREATE_INDEX_ALLOWLIST)) {
      expect(CREATE_INDEX.test(readFileSync(join(SRC, rel), "utf-8"))).toBe(true)
    }
  })
})
