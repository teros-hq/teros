/**
 * Remote Device Bindings Model
 *
 * Multi-workspace pairing (2026-10-20): separates device identity from app
 * binding. `remote_devices` holds pure identity (deviceId, hostname, os, …);
 * this collection holds the N:M relationship between devices and app
 * instances — one row per (deviceId, appId) pair.
 *
 * A device whose key is pasted into N app instances (across workspaces) gets
 * N bindings. The tunnel is per-device (one WebSocket), but each binding
 * lets that workspace's agents dispatch tools to the machine.
 *
 * Revocation is per-binding: removing one binding does NOT tear down the
 * tunnel while other bindings remain valid.
 */

import type { Collection, Db } from 'mongodb';
import { COLLECTIONS, collection, now } from '../db';

// ============================================================================
// TYPES
// ============================================================================

export type RemoteBindingStatus = 'active' | 'revoked';

export interface RemoteDeviceBinding {
  /** Stable id generated by the daemon at pairing (`dev_…`) */
  deviceId: string;
  /** Bound `mca.teros.remote` app instance */
  appId: string;
  /** Workspace the app instance belongs to (`apps.ownerId`) */
  workspaceId: string;
  /** User who pasted the device key into the app instance (credential owner) */
  ownerId: string;
  /** sha256 of the device key at time of binding */
  tokenHash: string;
  status: RemoteBindingStatus;
  boundAt: Date;
  updatedAt: Date;
}

/**
 * Registry port for the bindings collection. Mongo-backed in production;
 * tests use an in-memory fake.
 */
export interface RemoteDeviceBindingRegistry {
  /** Create-or-update a binding (idempotent per device+app). */
  upsertBinding(input: {
    deviceId: string;
    appId: string;
    workspaceId: string;
    ownerId: string;
    tokenHash: string;
  }): Promise<RemoteDeviceBinding>;
  /** Revoke a single binding (per-app). Does NOT affect other bindings. */
  revokeBinding(deviceId: string, appId: string): Promise<boolean>;
  /** Revoke ALL bindings for a device (full unpair). */
  revokeAllBindings(deviceId: string): Promise<number>;
  /** List all active bindings for a device. */
  getActiveByDeviceId(deviceId: string): Promise<RemoteDeviceBinding[]>;
  /** List all active bindings for an app instance. */
  getActiveByAppId(appId: string): Promise<RemoteDeviceBinding[]>;
  /** Get a specific binding. */
  getBinding(deviceId: string, appId: string): Promise<RemoteDeviceBinding | null>;
  /** Check if a device has any active binding. */
  hasActiveBinding(deviceId: string): Promise<boolean>;
}

// ============================================================================
// MONGO IMPLEMENTATION
// ============================================================================

export function getRemoteDeviceBindingsCollection(db: Db): Collection<RemoteDeviceBinding> {
  return collection<RemoteDeviceBinding>(db, COLLECTIONS.remoteDeviceBindings);
}

export class MongoRemoteDeviceBindingRegistry implements RemoteDeviceBindingRegistry {
  private readonly col: Collection<RemoteDeviceBinding>;

  constructor(db: Db) {
    this.col = getRemoteDeviceBindingsCollection(db);
  }

  async upsertBinding(input: {
    deviceId: string;
    appId: string;
    workspaceId: string;
    ownerId: string;
    tokenHash: string;
  }): Promise<RemoteDeviceBinding> {
    const ts = now();
    const doc = await this.col.findOneAndUpdate(
      { deviceId: input.deviceId, appId: input.appId },
      {
        $set: {
          workspaceId: input.workspaceId,
          ownerId: input.ownerId,
          tokenHash: input.tokenHash,
          status: 'active' as RemoteBindingStatus,
          updatedAt: ts,
        },
        $setOnInsert: {
          deviceId: input.deviceId,
          appId: input.appId,
          boundAt: ts,
        },
      },
      { upsert: true, returnDocument: 'after' },
    );
    if (!doc) throw new Error(`remote_device_bindings upsert returned no document for ${input.deviceId}/${input.appId}`);
    return doc;
  }

  async revokeBinding(deviceId: string, appId: string): Promise<boolean> {
    const result = await this.col.updateOne(
      { deviceId, appId, status: 'active' },
      { $set: { status: 'revoked' as RemoteBindingStatus, updatedAt: now() } },
    );
    return result.modifiedCount > 0;
  }

  async revokeAllBindings(deviceId: string): Promise<number> {
    const result = await this.col.updateMany(
      { deviceId, status: 'active' },
      { $set: { status: 'revoked' as RemoteBindingStatus, updatedAt: now() } },
    );
    return result.modifiedCount;
  }

  async getActiveByDeviceId(deviceId: string): Promise<RemoteDeviceBinding[]> {
    return this.col.find({ deviceId, status: 'active' }).toArray();
  }

  async getActiveByAppId(appId: string): Promise<RemoteDeviceBinding[]> {
    return this.col.find({ appId, status: 'active' }).toArray();
  }

  async getBinding(deviceId: string, appId: string): Promise<RemoteDeviceBinding | null> {
    return this.col.findOne({ deviceId, appId });
  }

  async hasActiveBinding(deviceId: string): Promise<boolean> {
    const count = await this.col.countDocuments({ deviceId, status: 'active' }, { limit: 1 });
    return count > 0;
  }
}
