/**
 * Remote Devices Model
 *
 * Persistent registry of machines paired through Teros Remote
 * (docs/specs/remote/teros-remote.md § Data Model, REQ-5). One record per
 * paired machine; the RemoteDeviceGateway creates it on the first
 * authenticated `hello` and keeps `status` / `lastSeenAt` current on every
 * connect, heartbeat and disconnect.
 *
 * The daemon owns the truth about its allowlist and exec toggle — the fields
 * mirrored here (`declaredAllowedRoots`, `execEnabled`, `capabilities`) are
 * informational, for the app panel and `device-status` (REQ-13).
 */

import type { Collection, Db } from 'mongodb';
import { COLLECTIONS, collection, newId, now } from '../db';

// ============================================================================
// TYPES
// ============================================================================

export type RemoteDeviceStatus = 'pending' | 'online' | 'offline' | 'revoked';

/**
 * Why a device was stopped by the backend (v1.1.0 keep-alive/TTL plane).
 * `stoppedReason` is set together with `stoppedAt` when the TTL checker
 * orders a clean shutdown; the offline diagnosis surfaces it to the user
 * ("disconnected by inactivity on <date> — run teros-remote start").
 */
export type RemoteDeviceStopReason = 'ttl_inactive' | 'revoked' | 'operator';

export interface RemoteDevice {
  /** Stable id generated by the daemon at pairing (`dev_…`) */
  deviceId: string;
  /** User-assigned machine name; defaults to the hostname reported in `hello` */
  name: string;
  /** User who pasted the device key into the app instance (credential owner) */
  ownerId: string;
  /** Workspace the app instance belongs to (`apps.ownerId`) */
  workspaceId: string;
  /** Bound `mca.teros.remote` app instance */
  appId: string;
  /** sha256 of the device key — mirrors the app instance's stored user secret */
  tokenHash: string;
  status: RemoteDeviceStatus;
  lastSeenAt?: Date;
  /**
   * Keep-alive/TTL plane (v1.1.0): last `keepalive` the backend sent down the
   * tunnel. The daemon's watchdog self-shuts-down when this goes stale.
   */
  lastKeepaliveAt?: Date;
  /**
   * Last user activity observed for the bound workspaces (session validation,
   * channel message, remote tool dispatch). Drives the inactivity TTL.
   */
  lastUserActivityAt?: Date;
  /** Set when the backend stopped the daemon (TTL expiry / operator). */
  stoppedAt?: Date;
  stoppedReason?: RemoteDeviceStopReason;
  hostname: string;
  os: string;
  arch: string;
  daemonVersion: string;
  /** Informational mirror of the daemon's `allowedRoots`; the daemon enforces its own config */
  declaredAllowedRoots: string[];
  /** Whether the daemon exposes `bash` at all (`exec.enabled`) */
  execEnabled: boolean;
  /** Tool names the daemon answers (from `hello`) */
  capabilities: string[];
  /** Gateway session of the current/last tunnel */
  sessionId?: string;
  /** Last error reported by the daemon through `health_update` */
  lastError?: string | null;
  createdAt: Date;
  updatedAt: Date;
}

/** What the gateway knows after a `hello` has been authenticated. */
export interface RemoteDeviceOnlineInput {
  deviceId: string;
  ownerId: string;
  workspaceId: string;
  appId: string;
  tokenHash: string;
  sessionId: string;
  hostname: string;
  /** Display name from the hello (falls back to hostname when absent). */
  name: string;
  os: string;
  arch: string;
  daemonVersion: string;
  declaredAllowedRoots: string[];
  execEnabled: boolean;
  capabilities: string[];
}

/**
 * Registry port used by the RemoteDeviceGateway. Mongo-backed in production
 * (`MongoRemoteDeviceRegistry`); tests use an in-memory fake.
 */
export interface RemoteDeviceRegistry {
  /** Create-or-update the record on an authenticated hello; flips status to `online`. */
  upsertOnline(input: RemoteDeviceOnlineInput): Promise<RemoteDevice>;
  /** Tunnel closed (or heartbeat lost). Only the owning session may flip the record offline. */
  markOffline(deviceId: string, sessionId: string): Promise<void>;
  /** Liveness touch (pong / health_update / tool_result). */
  touch(deviceId: string, patch?: { lastError?: string | null }): Promise<void>;
  /**
   * Keep-alive/TTL plane (v1.1.0): record that a `keepalive` was sent down the
   * tunnel. `markStoppedInactive` clears `stoppedAt`/`stoppedReason` on reconnect.
   */
  markKeepaliveSent(deviceId: string): Promise<void>;
  /**
   * Record observed user activity for the device's bound workspaces (renews the
   * TTL). Idempotent; called from the activity probe on every signal.
   */
  touchUserActivity(deviceId: string, at?: Date): Promise<void>;
  /**
   * Mark a device as stopped by the backend (TTL expiry / operator / revoked).
   * Does not touch the socket — the gateway owns the wire; this records state.
   */
  markStopped(deviceId: string, reason: RemoteDeviceStopReason): Promise<void>;
  /** All devices whose tunnel is currently online (TTL checker input). */
  listOnline(): Promise<RemoteDevice[]>;
  getByDeviceId(deviceId: string): Promise<RemoteDevice | null>;
  getByAppId(appId: string): Promise<RemoteDevice | null>;
  getByTokenHash(tokenHash: string): Promise<RemoteDevice | null>;
}

// ============================================================================
// MONGO IMPLEMENTATION
// ============================================================================

export function getRemoteDevicesCollection(db: Db): Collection<RemoteDevice> {
  return collection<RemoteDevice>(db, COLLECTIONS.remoteDevices);
}

export function newRemoteSessionId(): string {
  return newId('rsess');
}

export class MongoRemoteDeviceRegistry implements RemoteDeviceRegistry {
  private readonly col: Collection<RemoteDevice>;

  constructor(db: Db) {
    this.col = getRemoteDevicesCollection(db);
  }

  async upsertOnline(input: RemoteDeviceOnlineInput): Promise<RemoteDevice> {
    const ts = now();
    const doc = await this.col.findOneAndUpdate(
      { deviceId: input.deviceId },
      {
        $set: {
          ownerId: input.ownerId,
          workspaceId: input.workspaceId,
          appId: input.appId,
          tokenHash: input.tokenHash,
          sessionId: input.sessionId,
          status: 'online',
          lastSeenAt: ts,
          hostname: input.hostname,
          name: input.name,
          os: input.os,
          arch: input.arch,
          daemonVersion: input.daemonVersion,
          declaredAllowedRoots: input.declaredAllowedRoots,
          execEnabled: input.execEnabled,
          capabilities: input.capabilities,
          lastError: null,
          updatedAt: ts,
        },
        // Keep-alive/TTL plane (v1.1.0): a reconnect (user ran
        // `teros-remote start`) clears any previous backend-initiated stop.
        $unset: { stoppedAt: '', stoppedReason: '' },
        $setOnInsert: {
          deviceId: input.deviceId,
          createdAt: ts,
          // The user just reconnected the daemon — that IS user activity.
          lastUserActivityAt: ts,
        },
      },
      { upsert: true, returnDocument: 'after' },
    );
    if (!doc) throw new Error(`remote_devices upsert returned no document for ${input.deviceId}`);
    return doc;
  }

  async markOffline(deviceId: string, sessionId: string): Promise<void> {
    const ts = now();
    // A reconnect may already own the record (new sessionId) — never clobber it.
    await this.col.updateOne(
      { deviceId, sessionId, status: 'online' },
      { $set: { status: 'offline', lastSeenAt: ts, updatedAt: ts } },
    );
  }

  async touch(deviceId: string, patch: { lastError?: string | null } = {}): Promise<void> {
    const ts = now();
    await this.col.updateOne(
      { deviceId },
      {
        $set: {
          lastSeenAt: ts,
          updatedAt: ts,
          ...(patch.lastError !== undefined ? { lastError: patch.lastError } : {}),
        },
      },
    );
  }

  async markKeepaliveSent(deviceId: string): Promise<void> {
    const ts = now();
    await this.col.updateOne(
      { deviceId },
      { $set: { lastKeepaliveAt: ts, updatedAt: ts } },
    );
  }

  async touchUserActivity(deviceId: string, at: Date = now()): Promise<void> {
    // Never move the activity timestamp backwards (out-of-order signals).
    await this.col.updateOne(
      { deviceId, $or: [{ lastUserActivityAt: { $lt: at } }, { lastUserActivityAt: { $exists: false } }] },
      { $set: { lastUserActivityAt: at, updatedAt: now() } },
    );
  }

  async markStopped(deviceId: string, reason: RemoteDeviceStopReason): Promise<void> {
    const ts = now();
    await this.col.updateOne(
      { deviceId },
      { $set: { stoppedAt: ts, stoppedReason: reason, updatedAt: ts } },
    );
  }

  async listOnline(): Promise<RemoteDevice[]> {
    return this.col.find({ status: 'online' }).toArray();
  }

  getByDeviceId(deviceId: string): Promise<RemoteDevice | null> {
    return this.col.findOne({ deviceId });
  }

  getByAppId(appId: string): Promise<RemoteDevice | null> {
    return this.col.findOne({ appId });
  }

  getByTokenHash(tokenHash: string): Promise<RemoteDevice | null> {
    return this.col.findOne({ tokenHash });
  }
}
